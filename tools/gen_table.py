#!/usr/bin/env python3
"""Generate the octagonal table (face plate + maple border/pedestal), the scoreboard panel and the
placement-marker frames, as OBJ files with colliders.

Octagon: flat sides face +-X and +-Z (one per seat), vertices at 22.5 + 45k degrees.
Units are TTS world units; the face plate's top surface is local y = 0.
"""
from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "models"

FACE_APOTHEM = 21.0
BORDER_OUT = 23.2
PLATE_T = 0.3
MIRROR_X = True
COS = math.cos(math.radians(22.5))


class Mesh:
    def __init__(self):
        self.v, self.vt, self.vn, self.f = [], [], [], []

    def vert(self, p, uv, n):
        self.v.append(p)
        self.vt.append(uv)
        ln = math.sqrt(sum(c * c for c in n)) or 1.0
        self.vn.append(tuple(c / ln for c in n))
        return len(self.v) - 1

    def tri(self, a, b, c):
        self.f.append((a, b, c))

    def quad(self, a, b, c, d):
        self.f.append((a, b, c))
        self.f.append((a, c, d))

    def fix_winding(self):
        out = []
        for a, b, c in self.f:
            pa, pb, pc = self.v[a], self.v[b], self.v[c]
            e1 = [pb[i] - pa[i] for i in range(3)]
            e2 = [pc[i] - pa[i] for i in range(3)]
            cr = (e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0])
            n = [self.vn[a][i] + self.vn[b][i] + self.vn[c][i] for i in range(3)]
            out.append((a, c, b) if sum(cr[i] * n[i] for i in range(3)) < 0 else (a, b, c))
        self.f = out

    def write(self, path: Path, with_uv=True):
        self.fix_winding()
        sx = -1.0 if MIRROR_X else 1.0
        lines = [f"# {path.name}, generated by tools/gen_table.py"]
        lines += [f"v {sx * x:.4f} {y:.4f} {z:.4f}" for x, y, z in self.v]
        if with_uv:
            lines += [f"vt {u:.5f} {v:.5f}" for u, v in self.vt]
        lines += [f"vn {sx * x:.4f} {y:.4f} {z:.4f}" for x, y, z in self.vn]
        for a, b, c in self.f:
            if MIRROR_X:
                b, c = c, b
            if with_uv:
                lines.append(f"f {a + 1}/{a + 1}/{a + 1} {b + 1}/{b + 1}/{b + 1} {c + 1}/{c + 1}/{c + 1}")
            else:
                lines.append(f"f {a + 1}//{a + 1} {b + 1}//{b + 1} {c + 1}//{c + 1}")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print(f"  {path.relative_to(ROOT)}: {len(self.v)} verts, {len(self.f)} tris")


def oct_pt(apothem: float, k: int) -> tuple[float, float]:
    r = apothem / COS
    a = math.radians(22.5 + 45 * k)
    return r * math.cos(a), r * math.sin(a)


def seg_normal(k: int) -> tuple[float, float]:
    a = math.radians(45 * (k + 1))  # mid-angle between vertex k and k+1
    return math.cos(a), math.sin(a)


# --- face plate --------------------------------------------------------------------

def face_plate() -> Mesh:
    m = Mesh()
    span = 2 * FACE_APOTHEM / COS
    def uv(x, z):
        return (x / span + 0.5, z / span + 0.5)
    c = m.vert((0, 0, 0), uv(0, 0), (0, 1, 0))
    ring = [m.vert((x, 0, z), uv(x, z), (0, 1, 0)) for x, z in (oct_pt(FACE_APOTHEM, k) for k in range(8))]
    for k in range(8):
        m.tri(c, ring[k], ring[(k + 1) % 8])
    cb = m.vert((0, -PLATE_T, 0), (0.5, 0.5), (0, -1, 0))
    ringb = [m.vert((x, -PLATE_T, z), (0.5, 0.5), (0, -1, 0)) for x, z in (oct_pt(FACE_APOTHEM, k) for k in range(8))]
    for k in range(8):
        m.tri(cb, ringb[(k + 1) % 8], ringb[k])
    for k in range(8):
        n = seg_normal(k)
        (x0, z0), (x1, z1) = oct_pt(FACE_APOTHEM, k), oct_pt(FACE_APOTHEM, (k + 1) % 8)
        a = m.vert((x0, 0, z0), (0.5, 0.5), (n[0], 0, n[1]))
        b = m.vert((x1, 0, z1), (0.5, 0.5), (n[0], 0, n[1]))
        cc = m.vert((x1, -PLATE_T, z1), (0.5, 0.5), (n[0], 0, n[1]))
        d = m.vert((x0, -PLATE_T, z0), (0.5, 0.5), (n[0], 0, n[1]))
        m.quad(a, b, cc, d)
    return m


# --- border (maple bullnose rail + apron + pedestal) ----------------------------------------

def border_profile():
    """(r, y) points from the inner bottom edge, over the rail, down the apron, back inward."""
    pts = [(FACE_APOTHEM, -PLATE_T), (FACE_APOTHEM, 0.35)]
    r_in, r_out, top, rad = FACE_APOTHEM, BORDER_OUT, 0.75, 0.4
    for i in range(1, 7):                                       # inner round-over
        a = math.radians(180 - 90 * i / 6)
        pts.append((r_in + rad + rad * math.cos(a), top - rad + rad * math.sin(a)))
    for i in range(1, 7):                                       # outer round-over
        a = math.radians(90 - 90 * i / 6)
        pts.append((r_out - rad + rad * math.cos(a), top - rad + rad * math.sin(a)))
    pts += [(r_out, -1.1), (r_out - 0.5, -1.1), (r_out - 0.5, -0.6), (FACE_APOTHEM - 0.5, -0.6), (FACE_APOTHEM - 0.5, -PLATE_T)]
    return pts


def border() -> Mesh:
    m = Mesh()
    prof = border_profile()
    # cumulative profile length for v
    lens = [0.0]
    for i in range(1, len(prof)):
        lens.append(lens[-1] + math.dist(prof[i - 1], prof[i]))
    total = lens[-1]
    for k in range(8):
        n2 = seg_normal(k)
        for i in range(len(prof) - 1):
            (r0, y0), (r1, y1) = prof[i], prof[i + 1]
            tr, ty = r1 - r0, y1 - y0
            # profile normal: rotate tangent; outward/upward chosen by fix_winding consistency
            pn = (ty, -tr)
            if i < len(prof) - 1 and (pn[1] < 0 and y0 > 0.3):
                pn = (-pn[0], -pn[1])
            # decide orientation: rail top points up, apron outside points out, underside points down
            mid_r, mid_y = (r0 + r1) / 2, (y0 + y1) / 2
            if abs(tr) < 1e-6:     # vertical wall
                pn = (1.0, 0.0) if mid_r > (FACE_APOTHEM + BORDER_OUT) / 2 or (mid_r < FACE_APOTHEM and False) else (-1.0, 0.0)
                if abs(mid_r - (BORDER_OUT - 0.5)) < 1e-3:
                    pn = (-1.0, 0.0)
                if abs(mid_r - (FACE_APOTHEM - 0.5)) < 1e-3:
                    pn = (-1.0, 0.0)
            elif abs(ty) < 1e-6:   # horizontal
                pn = (0.0, 1.0) if mid_y > 0 else (0.0, -1.0)
            else:                  # arcs: normal points away from the arc centre
                cr = FACE_APOTHEM + 0.4 if mid_r < (FACE_APOTHEM + BORDER_OUT) / 2 else BORDER_OUT - 0.4
                pn = (mid_r - cr, mid_y - (0.75 - 0.4))
            ids = []
            for (r, y), ln in (((r0, y0), lens[i]), ((r1, y1), lens[i + 1])):
                for kk in (k, (k + 1) % 8):
                    x, z = oct_pt(r, kk)
                    s = (kk == k) and 0.0 or 1.0
                    ids.append(m.vert((x, y, z), (0.05 + 0.9 * s, ln / total),
                                      (pn[0] * n2[0], pn[1], pn[0] * n2[1])))
            a, b, c, d = ids[0], ids[1], ids[3], ids[2]
            m.quad(a, b, c, d)
    # pedestal: octagonal column and foot
    def prism(r, y0, y1, uv_v0):
        for k in range(8):
            n2 = seg_normal(k)
            (x0, z0), (x1, z1) = oct_pt(r, k), oct_pt(r, (k + 1) % 8)
            a = m.vert((x0, y0, z0), (0.1, uv_v0), (n2[0], 0, n2[1]))
            b = m.vert((x1, y0, z1), (0.9, uv_v0), (n2[0], 0, n2[1]))
            c = m.vert((x1, y1, z1), (0.9, uv_v0 + 0.3), (n2[0], 0, n2[1]))
            d = m.vert((x0, y1, z0), (0.1, uv_v0 + 0.3), (n2[0], 0, n2[1]))
            m.quad(a, b, c, d)

    def cap(r, y, up):
        c = m.vert((0, y, 0), (0.5, 0.5), (0, 1 if up else -1, 0))
        ring = [m.vert((x, y, z), (0.5 + x / (4 * r), 0.5 + z / (4 * r)), (0, 1 if up else -1, 0))
                for x, z in (oct_pt(r, k) for k in range(8))]
        for k in range(8):
            m.tri(c, ring[k], ring[(k + 1) % 8])

    prism(3.0, -16.0, -0.6, 0.1)
    prism(9.0, -17.0, -16.0, 0.5)
    cap(9.0, -16.0, True)
    cap(9.0, -17.0, False)
    cap(FACE_APOTHEM - 0.5, -0.6, False)
    return m


def border_collider() -> Mesh:
    """Low-poly rail ring (non-convex; the table is locked so TTS may use it as a mesh collider)."""
    m = Mesh()
    prof = [(FACE_APOTHEM, 0.0), (FACE_APOTHEM, 0.75), (BORDER_OUT, 0.75), (BORDER_OUT, -1.1), (FACE_APOTHEM, -1.1)]
    for k in range(8):
        n2 = seg_normal(k)
        for i in range(len(prof)):
            (r0, y0), (r1, y1) = prof[i], prof[(i + 1) % len(prof)]
            mid = ((r0 + r1) / 2, (y0 + y1) / 2)
            pn = (mid[0] - (FACE_APOTHEM + BORDER_OUT) / 2, mid[1] + 0.2)
            ids = []
            for r, y in ((r0, y0), (r1, y1)):
                for kk in (k, (k + 1) % 8):
                    x, z = oct_pt(r, kk)
                    ids.append(m.vert((x, y, z), (0, 0), (pn[0] * n2[0], pn[1], pn[0] * n2[1])))
            m.quad(ids[0], ids[1], ids[3], ids[2])
    return m


# --- scoreboard panel --------------------------------------------------------------------------

def box(m: Mesh, x0, x1, y0, y1, z0, z1, front_uv=None, other_uv=(0.0, 0.0, 1.0, 0.25)):
    """Axis-aligned box. front (-Z face) may use its own UV rect (u0, v0, u1, v1)."""
    def rect(face, corners, n, uvr):
        u0, v0, u1, v1 = uvr
        uvs = [(u0, v0), (u1, v0), (u1, v1), (u0, v1)]
        ids = [m.vert(p, uvs[i], n) for i, p in enumerate(corners)]
        m.quad(*ids)
    fu = front_uv or other_uv
    rect("front", [(x1, y0, z0), (x0, y0, z0), (x0, y1, z0), (x1, y1, z0)], (0, 0, -1), fu)
    rect("back", [(x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)], (0, 0, 1), other_uv)
    rect("top", [(x0, y1, z0), (x0, y1, z1), (x1, y1, z1), (x1, y1, z0)], (0, 1, 0), other_uv)
    rect("bottom", [(x0, y0, z1), (x0, y0, z0), (x1, y0, z0), (x1, y0, z1)], (0, -1, 0), other_uv)
    rect("left", [(x0, y0, z0), (x0, y0, z1), (x0, y1, z1), (x0, y1, z0)], (-1, 0, 0), other_uv)
    rect("right", [(x1, y0, z1), (x1, y0, z0), (x1, y1, z0), (x1, y1, z1)], (1, 0, 0), other_uv)


def scoreboard() -> Mesh:
    """Upright panel 14 x 9.5; the chalk surface faces local -Z. Texture: top 3/4 slate, bottom 1/4 wood."""
    m = Mesh()
    W, H, D, F = 14.0, 9.5, 0.4, 0.5
    slate_uv = (0.0, 0.25, 1.0, 1.0)
    wood_uv = (0.0, 0.0, 1.0, 0.25)
    box(m, -W / 2 + F, W / 2 - F, F, H - F, -D / 2 + 0.08, D / 2, front_uv=slate_uv, other_uv=wood_uv)
    for x0, x1, y0, y1 in ((-W / 2, W / 2, 0, F), (-W / 2, W / 2, H - F, H),
                           (-W / 2, -W / 2 + F, F, H - F), (W / 2 - F, W / 2, F, H - F)):
        box(m, x0, x1, y0, y1, -D / 2, D / 2, other_uv=wood_uv)
    # feet
    box(m, -W / 2 + 1, -W / 2 + 2, -0.0, 0.3, -1.6, 1.6, other_uv=wood_uv)
    box(m, W / 2 - 2, W / 2 - 1, -0.0, 0.3, -1.6, 1.6, other_uv=wood_uv)
    return m


def scoreboard_collider() -> Mesh:
    m = Mesh()
    box(m, -7, 7, 0, 9.5, -0.3, 0.3)
    return m


# --- placement markers --------------------------------------------------------------------------

def frame(L=2.0, W=1.0, t=0.09, h=0.05, cross=False) -> Mesh:
    """Flat rectangular outline (optionally with an X) used for legal/rejected positions."""
    m = Mesh()
    hl, hw = L / 2 + 0.06, W / 2 + 0.06
    bars = [(-hl, hl, hw - t, hw), (-hl, hl, -hw, -hw + t), (-hl, -hl + t, -hw, hw), (hl - t, hl, -hw, hw)]
    for x0, x1, z0, z1 in bars:
        box(m, x0, x1, 0, h, z0, z1)
    if cross:
        for sgn in (1, -1):
            n = 16
            for i in range(n):
                xa = -hl + 2 * hl * i / n
                xb = -hl + 2 * hl * (i + 1) / n
                za, zb = sgn * (-hw + 2 * hw * i / n), sgn * (-hw + 2 * hw * (i + 1) / n)
                box(m, min(xa, xb), max(xa, xb), 0, h, min(za, zb) - t / 2, max(za, zb) + t / 2)
    return m


def main():
    face_plate().write(OUT / "table" / "table_face.obj")
    border().write(OUT / "table" / "table_border.obj")
    border_collider().write(OUT / "table" / "table_border_collider.obj", with_uv=False)
    scoreboard().write(OUT / "board" / "scoreboard.obj")
    scoreboard_collider().write(OUT / "board" / "scoreboard_collider.obj", with_uv=False)
    frame().write(OUT / "markers" / "marker_ok.obj")
    frame(cross=True).write(OUT / "markers" / "marker_bad.obj")
    frame(L=9.6, W=3.4, t=0.1, h=0.03).write(OUT / "markers" / "rack_zone.obj")


if __name__ == "__main__":
    main()
